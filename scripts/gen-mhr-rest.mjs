// Regenerates src/three/poseFinder/mhrRest.js from Meta's MHR assets (Apache-2.0, github.com/facebookresearch/MHR).
// Usage: node scripts/gen-mhr-rest.mjs path/to/assets/lod6.fbx
// Only the skeleton (names, parents, rest pose) is read; no mesh data is kept.
import fs from 'node:fs'
import * as THREE from 'three'
import { FBXLoader } from 'three/examples/jsm/loaders/FBXLoader.js'

const src = process.argv[2]
if (!src) { console.error('usage: node scripts/gen-mhr-rest.mjs <lod6.fbx>'); process.exit(1) }
const buf = fs.readFileSync(src)
const root = new FBXLoader().parse(buf.buffer.slice(buf.byteOffset, buf.byteOffset + buf.byteLength), '')
root.updateMatrixWorld(true)
const bones = []
root.traverse((o) => { if (o.isBone) bones.push(o) })
if (bones.length !== 127) throw new Error(`expected 127 MHR joints, found ${bones.length}`)
const index = new Map(bones.map((b, i) => [b, i]))
const r = (v, d) => +v.toFixed(d)
const names = bones.map((b) => b.name)
const parents = bones.map((b) => (index.has(b.parent) ? index.get(b.parent) : -1))
const pos = [], quat = []
const p = new THREE.Vector3(), q = new THREE.Quaternion(), s = new THREE.Vector3()
for (const b of bones) {
  b.matrixWorld.decompose(p, q, s)
  pos.push(r(p.x, 4), r(p.y, 4), r(p.z, 4))
  quat.push(r(q.x, 6), r(q.y, 6), r(q.z, 6), r(q.w, 6))
}
const out = `// GENERATED by scripts/gen-mhr-rest.mjs from Meta's MHR skeleton (Apache-2.0). Do not edit by hand.
// 127 MHR joints in the model's own y-up frame: world REST positions (centimetres) and world REST orientations
// (quaternions x,y,z,w). Needed because the model reports posed GLOBAL rotations, and BVH wants rotation relative to rest.
export const MHR_JOINT_COUNT = 127
export const MHR_NAMES = ${JSON.stringify(names)}
export const MHR_PARENTS = ${JSON.stringify(parents)}
export const MHR_REST_POS_CM = new Float32Array(${JSON.stringify(pos)})
export const MHR_REST_QUAT = new Float32Array(${JSON.stringify(quat)})
`
fs.writeFileSync('src/three/poseFinder/mhrRest.js', out)
console.log('wrote', out.length, 'bytes')
